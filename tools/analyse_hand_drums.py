"""Measure hand-drum hits at 48 kHz. No audio or phase data is written to the report."""
import argparse
import json
import subprocess
import math
import sys
import soundfile as sf
from pathlib import Path

import numpy as np
from scipy import signal

SR = 48000
# Fractions of a second after onset. One RMS envelope per residual band.
TIMES = np.array([.003, .010, .023, .045, .085, .15, .25, .40, .65, 1.0])
BANDS = [(35, 250), (250, 950), (950, 3200), (3200, 10000)]


def read(path):
    if path.suffix.lower()==".wav":
        data, rate = sf.read(path, always_2d=True)
        x = data.mean(axis=1)
        if rate != SR:
            factor = math.gcd(rate, SR)
            x = signal.resample_poly(x, SR//factor, rate//factor)
    else:
        raw = subprocess.check_output(["ffmpeg", "-v", "error", "-i", str(path), "-ac", "1",
                                       "-ar", str(SR), "-f", "f32le", "-"])
        x = np.frombuffer(raw, dtype="<f4").astype(float)
    if len(x)<256 or np.max(abs(x))<1e-8:
        raise ValueError("empty or silent")
    onset = np.flatnonzero(abs(x) > np.max(abs(x)) * .018)[0]
    return x[onset:] / np.max(abs(x))


def measure(path):
    x = read(path)
    # A common observation length also keeps the noise floor of long files out of the fit.
    x = np.pad(x[:SR], (0, max(0, SR-len(x))))
    energy = np.cumsum(x*x)
    t90 = np.searchsorted(energy, .9*energy[-1]) / SR
    # Search early and late spectra so a short upper mode can survive a long bass tail.
    spectra = []
    for start, end in [(0, .065), (.022, .15), (.075, .28)]:
        segment = x[int(SR*start):int(SR*end)]
        window = np.hanning(len(segment))
        spectra.append(abs(np.fft.rfft(segment*window, 32768))/sum(window))
    spectrum = np.maximum.reduce(spectra)
    bins, _ = signal.find_peaks(spectrum, distance=13)
    bins = [k for k in bins if 42 < k*SR/32768 < 4000]
    peaks = sorted(bins, key=lambda k: -spectrum[k])[:8]
    modes = []
    for k in peaks:
        hz = k*SR/32768
        # Narrow-band envelope. Estimate decay from high-SNR points before the room tail.
        width = max(14, min(75, hz*.14))
        filt = signal.butter(2, [hz-width, hz+width], fs=SR, btype="bandpass", output="sos")
        env = abs(signal.hilbert(signal.sosfilt(filt, x)))
        t = np.arange(.012, .42, .006)
        amp = np.array([np.median(env[int(SR*v):int(SR*(v+.006))]) for v in t])
        i = np.argmax(amp)
        mask = (t >= t[i]) & (amp > amp[i]*.09)
        tau = .008
        if sum(mask) >= 3:
            slope = np.polyfit(t[mask], np.log(amp[mask]), 1)[0]
            tau = np.clip(-1/min(-2, slope), .008, .45)
        modes.append([round(hz,1), round(float(amp[i]),4), round(float(tau),4)])
    band_env = []
    for lo, hi in BANDS:
        y = signal.sosfilt(signal.butter(2, [lo, hi], fs=SR, btype="bandpass", output="sos"), x)
        band_env.append([round(float(np.sqrt(np.mean(y[max(0,int(SR*t)-192):int(SR*t)+192]**2))),5)
                         for t in TIMES])
    return dict(t90_ms=round(1000*t90), modes=modes, strengths=[round(float(spectrum[k]),6) for k in peaks], bands=band_env)


# Stroke, radial zone (inside/outside), force (soft/medium/hard).
# Numbered library WAVs have no gesture metadata. This is an acoustic mapping.
FRAME = [
    [[31, 15, 21], [34, 38, 1]], [[11, 4, 17], [7, 14, 3]],
    [[13, 16, 19], [41, 5, 42]], [[50, 18, 44], [9, 6, 51]],
    [[37, 45, 10], [49, 43, 46]],
]
PAKH = ["e", "d", "g", "f", "c"]


def write_profiles(measured, path, baseline=None):
    from scipy.special import jn_zeros, jv
    def array(values):
        return "{"+", ".join(f"{v:.5f}f" for v in values)+"}"
    out = ["// Generated by tools/analyse_hand_drums.py from stroke measurements.",
           "#pragma once", "namespace optisynth::handdrum {",
           "struct Pole {float hz, gain, tau;};",
           "struct StrokeFit {Pole poles[6]; float contact[3]; float noiseTime;};",
           "inline constexpr int frameFiles[5][2][3]={"]
    for zones in FRAME:
        out.append("    {"+", ".join("{"+", ".join(map(str, zone))+"}" for zone in zones)+"},")
    out+=["};","inline constexpr StrokeFit fits[]={"]
    names=[f"FRD_FrameDrums_{n:02d}.wav" for group in FRAME for zone in group for n in zone]
    names += [f"{k}1-{v}.m4a" for k in PAKH for v in (1,2,3)]
    # A second pass can compensate for losses introduced by the excitation and
    # spatial weights. Only correct identified lines in strokes where the wrong
    # peak dominates. Leave unmeasured radial zones at their initial fit.
    calibration = {}
    if baseline:
        for i, key in enumerate((0, 2, 4, 5, 7)):
            for v in range(3):
                calibration[f"FRD_FrameDrums_{FRAME[i][0][v]:02d}.wav"] = baseline[f"Frame drum-{key}-{v}.wav"]
                calibration[f"{PAKH[i]}1-{v+1}.m4a"] = baseline[f"Pakhawaj-{key}-{v}.wav"]
    for name in names:
        m=measured[name]
        poles=np.array(m["modes"][:6])
        # Match weighted modal energy decay to the observed duration of this particular hit.
        # A narrow filter can count a neighbouring strong mode twice. Use the
        # resolved line magnitudes for gain and the band envelopes for loss.
        gain=np.array(m["strengths"][:6])
        poles[:,1]=gain
        def t90(scale):
            tau=poles[:,2]*scale
            t=np.linspace(0,1,1001)
            e=(gain**2*tau)*(1-np.exp(-2*t[:,None]/tau))
            return np.searchsorted(e.sum(axis=1), .9*e[-1].sum())*.001
        lo,hi=.1,4.
        for _ in range(16):
            mid=(lo+hi)/2
            if t90(mid)<.001*m["t90_ms"]:lo=mid
            else:hi=mid
        poles[:,2]*=(lo+hi)/2
        poles[:,1]/=np.linalg.norm(gain)
        dry = calibration.get(name)
        if dry and abs(dry["modes"][0][0]/poles[0,0]-1) > .05:
            hz = np.array(dry["modes"])[:,0]
            ratios = np.ones(6)
            identified = []
            for i, (target, strength) in enumerate(zip(poles[:,0], gain)):
                j = np.argmin(abs(hz-target))
                if abs(hz[j]-target) < max(4., .02*target):
                    ratios[i] = strength/max(1e-9,dry["strengths"][j])
                    identified.append(i)
            if identified:
                ratios[identified] /= np.median(ratios[identified])
                poles[:,1] *= np.clip(ratios, .55, 2.)
                poles[:,1] /= np.linalg.norm(poles[:,1])
        bands=np.array(m["bands"])
        contact=np.max(bands[1:,:3],axis=1)
        noise_tau=np.clip(-.020/np.log(np.clip(bands[2,2]/max(.0001,bands[2,0]),.025,.65)),.006,.045)
        out.append("    {{"+", ".join(array(row) for row in poles)+"}, "+array(contact)+f", {noise_tau:.5f}f"+"}, // "+name)
    out+=["};","inline constexpr float radial[6][9]={"]
    for order,root in [(0,1),(1,1),(2,1),(0,2),(3,1),(1,2)]:
        values=jv(order,jn_zeros(order,root)[-1]*np.linspace(.08,.90,9))
        out.append("    "+array(values/max(abs(values)))+",")
    out+=["};","} // namespace optisynth::handdrum"]
    path.write_text("\n".join(out)+"\n")


if __name__ == "__main__":
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("files",nargs="+",type=Path)
    parser.add_argument("--out",required=True,type=Path)
    parser.add_argument("--profiles",type=Path,help="Write fitted C++ drum tables")
    parser.add_argument("--baseline-renders",type=Path,help="Measurements of the first-pass synthetic strokes for modal gain correction")
    args=parser.parse_args()
    result={}
    for path in args.files:
        try:
            result[path.name]=measure(path)
        except (ValueError, RuntimeError) as error:
            print(f"Skipped {path.name}: {error}",file=sys.stderr)
    args.out.write_text(json.dumps(result,indent=2)+"\n")
    if args.profiles:
        write_profiles(result,args.profiles,json.loads(args.baseline_renders.read_text()) if args.baseline_renders else None)
